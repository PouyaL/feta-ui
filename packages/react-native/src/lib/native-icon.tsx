type Props = IconProps & {
  /** Icon name, for development warnings. */
  icon: string
  iconStyle: Style
  /** The icon's elements, generated by scripts/generate-react-native.ts. */
  tree: IconTree
  dir: 1 | -1
}

type Loose = ComponentType<Record<string, unknown> & { children?: ReactNode }>
const loose = (c: unknown): Loose => c as Loose

const STATIC: Record<string, Loose> = {
  path: loose(Path), g: loose(G), circle: loose(Circle), ellipse: loose(Ellipse), rect: loose(Rect), use: loose(Use), defs: loose(Defs),
  linearGradient: loose(LinearGradient), stop: loose(Stop), clipPath: loose(ClipPath), filter: loose(Filter), feGaussianBlur: loose(FeGaussianBlur),
}

const ANIMATED: Record<string, Loose> = {
  path: loose(Animated.createAnimatedComponent(Path)), circle: loose(Animated.createAnimatedComponent(Circle)),
  ellipse: loose(Animated.createAnimatedComponent(Ellipse)), rect: loose(Animated.createAnimatedComponent(Rect)),
  use: loose(Animated.createAnimatedComponent(Use)), g: loose(Animated.createAnimatedComponent(G)),
}

/** The fetaUI ink (DESIGN.md §1): a device has no currentColor to inherit. */
export const DEFAULT_INK = '#141812'
const NEON_OUTER = 0.55
const OUT = [0.23, 1, 0.32, 1] as const
const easeOutFill = bezier(0, 0, 0.58, 1)

// One reduced motion subscription for every icon on screen: a single bridge read and a single listener, started by the
// first icon to mount and dropped when the last one unmounts. The value is kept between mounts, and read again on the
// next first mount, so icons never wait on their own bridge call.
let reduceValue = false
const reduceSubs = new Set<() => void>()
let reduceStop: (() => void) | null = null

function setReduce(next: boolean): void {
  if (next === reduceValue) return
  reduceValue = next
  for (const fn of reduceSubs) fn()
}

function subscribeReduce(fn: () => void): () => void {
  reduceSubs.add(fn)
  if (reduceSubs.size === 1) {
    let live = true
    void AccessibilityInfo.isReduceMotionEnabled().then((v) => { if (live) setReduce(v) })
    const sub = AccessibilityInfo.addEventListener('reduceMotionChanged', setReduce)
    reduceStop = () => { live = false; sub.remove() }
  }
  return () => {
    reduceSubs.delete(fn)
    if (reduceSubs.size === 0) { reduceStop?.(); reduceStop = null }
  }
}

const readReduce = (): boolean => reduceValue

/** True when the person asked for less motion. Read through AccessibilityInfo and kept current without a restart. */
export function useReducedMotionSetting(): boolean {
  return useSyncExternalStore(subscribeReduce, readReduce, readReduce)
}

/** Draw window for part `i` as fractions of the preset duration: the body first, then details (as web). */
export function drawWindow(i: number): { start: number; end: number } {
  if (i === 0) return { start: 0, end: 0.75 }
  const start = 0.35 + Math.min(i - 1, 5) * 0.12
  return { start, end: start + 0.5 }
}

type Mode = 'idle' | 'draw' | 'swap'

/** `anim` is null for the idle icon: plain shapes, no shared values anywhere in the tree. */
type Ctx = { mode: Mode; anim: { t: SharedValue<number>; glowK: SharedValue<number> | null; ease: Ease } | null; glowColor: string | undefined }

/** Props for react-native-svg: metadata dropped, the Neon glow recoloured when a colour is set. */
function propsOf(raw: Readonly<Record<string, string | number>>, glowColor: string | undefined): Record<string, string | number> {
  const out: Record<string, string | number> = {}
  for (const [k, v] of Object.entries(raw)) if (!k.endsWith('$')) out[k] = v
  if (glowColor && typeof raw['glow$'] === 'string') for (const k of raw['glow$'].split(',')) out[k] = glowColor
  return out
}

function DrawShape({ tag, props, t, part, len, fillOnly, ease }: { tag: string; props: Record<string, string | number>; t: SharedValue<number>; part: number; len: number; fillOnly: string | null; ease: Ease }) {
  const Comp = ANIMATED[tag] ?? STATIC[tag] ?? loose(Path)
  const { start, end } = drawWindow(part)
  const animatedProps = useAnimatedProps(() => {
    const raw = (t.value - start) / (end - start)
    const local = raw <= 0 ? 0 : raw >= 1 ? 1 : raw
    const k = ease(local)
    const out: Record<string, number> = { strokeDashoffset: len * (1 - k), opacity: raw > 0 ? 1 : 0 }
    // Fill styles trace the outline, then fill in from 45 % of the stroke (ANIMATION.md §4).
    if (fillOnly !== null) out['fillOpacity'] = local < 0.45 ? 0 : easeOutFill((local - 0.45) / 0.55)
    return out
  })
  const outline = fillOnly !== null ? { stroke: fillOnly, strokeWidth: 1, strokeLinejoin: 'round' } : {}
  return <Comp {...props} {...outline} strokeDasharray={[len, len]} animatedProps={animatedProps} />
}

const REST_OPACITY = [1, 0, 0, 1]
const ACTIVE_OPACITY = [0, 1, 1, 0]

/** A state group of a two-state icon: the rest state fades out as the second fades in, holds, then back. */
function StateGroup({ state, t, times, ease, children, props }: { state: string; t: SharedValue<number>; times: readonly number[]; ease: Ease; children: ReactNode; props: Record<string, string | number> }) {
  const values = state === 'active' ? ACTIVE_OPACITY : REST_OPACITY
  const keys = [...times]
  // The ease runs inside each keyframe segment, as on web, so the hold keeps its full length.
  const animatedProps = useAnimatedProps(() => {
    const v = t.value
    let i = 0
    while (i < keys.length - 2 && v > (keys[i + 1] ?? 1)) i++
    const a = keys[i] ?? 0, b = keys[i + 1] ?? 1
    const local = b > a ? Math.min(1, Math.max(0, (v - a) / (b - a))) : 1
    const from = values[i] ?? 0, to = values[i + 1] ?? 0
    return { opacity: from + (to - from) * ease(local) }
  })
  const G2 = ANIMATED['g'] ?? loose(G)
  return <G2 {...props} animatedProps={animatedProps}>{children}</G2>
}

function GlowGroup({ glowK, props, children }: { glowK: SharedValue<number>; props: Record<string, string | number>; children: ReactNode }) {
  const animatedProps = useAnimatedProps(() => ({ opacity: NEON_OUTER * glowK.value }))
  const G2 = ANIMATED['g'] ?? loose(G)
  return <G2 {...props} animatedProps={animatedProps}>{children}</G2>
}

function render(nodes: IconTree, ctx: Ctx, path: string): ReactNode[] {
  return nodes.map(([tag, raw, kids], i) => {
    const key = `${path}${i}`
    const props = propsOf(raw, ctx.glowColor)
    const children = kids ? render(kids, ctx, `${key}.`) : undefined
    const len = raw['len$']
    const anim = ctx.anim
    if (anim && ctx.mode === 'draw' && typeof len === 'number') {
      const fillOnly = typeof raw['fillOnly$'] === 'string' ? raw['fillOnly$'] : null
      return <DrawShape key={key} tag={tag} props={props} t={anim.t} part={Number(raw['part$'] ?? 0)} len={len} fillOnly={fillOnly} ease={anim.ease} />
    }
    const state = raw['state$']
    if (anim && ctx.mode === 'swap' && tag === 'g' && typeof state === 'string') {
      return <StateGroup key={key} state={state} t={anim.t} times={presetSpecs.swap.times ?? [0, 0.15, 0.85, 1]} ease={anim.ease} props={props}>{children}</StateGroup>
    }
    if (anim?.glowK && tag === 'g' && raw['role$'] === 'glow-outer') return <GlowGroup key={key} glowK={anim.glowK} props={props}>{children}</GlowGroup>
    const Comp = STATIC[tag]
    if (!Comp) throw new Error(`fetaUI: <${tag}> is not supported`)
    return <Comp key={key} {...props}>{children}</Comp>
  })
}

const has = (nodes: IconTree, test: (raw: Readonly<Record<string, string | number>>) => boolean): boolean =>
  nodes.some(([, raw, kids]) => test(raw) || (kids ? has(kids, test) : false))

const maxPart = (nodes: IconTree): number =>
  nodes.reduce((m, [, raw, kids]) => Math.max(m, typeof raw['part$'] === 'number' ? raw['part$'] : -1, kids ? maxPart(kids) : -1), -1)

/** A tween over evenly spaced keyframes, or a quick move to the peak then a spring to rest (as web). */
function track(values: readonly number[], spec: PresetSpec, seconds: number, scale: number, done?: (finished?: boolean) => void): number {
  const v = values.map((x) => x * scale)
  const ease = spec.ease
  if (typeof ease === 'object' && !Array.isArray(ease) && 'stiffness' in ease) {
    const peaks = v.slice(1, -1)
    const each = (seconds * 0.35 * 1000) / Math.max(1, peaks.length)
    const steps = peaks.map((p) => withTiming(p, { duration: each, easing: Easing.bezier(OUT[0], OUT[1], OUT[2], OUT[3]) }))
    return withSequence(...steps, withSpring(v[v.length - 1] ?? 0, { stiffness: ease.stiffness, damping: ease.damping, mass: 1 }, done))
  }
  const easing = Array.isArray(ease) ? Easing.bezier(ease[0] as number, ease[1] as number, ease[2] as number, ease[3] as number) : Easing.linear
  const each = (seconds * 1000) / Math.max(1, v.length - 1)
  const steps = v.slice(1).map((p, k, arr) => withTiming(p, { duration: each, easing }, k === arr.length - 1 ? done : undefined))
  return steps.length ? withSequence(...steps) : withTiming(v[0] ?? 0, { duration: 0 }, done)
}

/** Transform origin from a CSS origin like 'top center', as percentages of the icon box. */
function originOf(origin: string): string {
  const w = origin.split(/\s+/)
  const y = w.includes('top') ? 0 : w.includes('bottom') ? 100 : 50
  const x = w.includes('left') ? 0 : w.includes('right') ? 100 : 50
  return `${x}% ${y}%`
}

type RunKind = 'draw' | 'swap' | 'move' | 'cue' | 'flicker'
type Run = { kind: RunKind; key: number }

type RunnerProps = {
  kind: RunKind
  iconStyle: Style
  tree: IconTree
  dir: 1 | -1
  size: number
  color: string | undefined
  preset: Preset
  seconds: number
  lastPart: number
  neon: boolean
  /** Called once, on the JS thread, when the run reaches rest. */
  onFinish: () => void
}

/**
 * One run of an icon. It owns every shared value, the moving view and the animated shapes, so none of them exist
 * while the icon is still. It mounts when a run starts and the icon unmounts it at rest, a picture identical to the
 * idle one (every part drawn, every transform back at zero).
 */
function Runner({ kind, iconStyle, tree, dir, size, color, preset, seconds, lastPart, neon, onFinish }: RunnerProps) {
  const t = useSharedValue(0)
  const tx = useSharedValue(0)
  const ty = useSharedValue(0)
  const scale = useSharedValue(1)
  const scaleY = useSharedValue(1)
  const rotate = useSharedValue(0)
  const opacity = useSharedValue(1)
  const glowK = useSharedValue(1)

  const spec = presetSpecs[preset]
  const origin = kind === 'move' ? originOf(spec.origin) : '50% 50%'
  const ease = useMemo(() => easeOf(spec.ease), [spec])
  const glowColor = iconStyle === 'neon' ? color : undefined
  const animGlow = kind === 'flicker' && neon

  const body = useMemo(
    () => render(tree, { mode: kind === 'draw' ? 'draw' : kind === 'swap' ? 'swap' : 'idle', anim: { t, glowK: animGlow ? glowK : null, ease }, glowColor }, ''),
    [tree, kind, t, animGlow, glowK, glowColor, ease],
  )

  useEffect(() => {
    const done = (finished?: boolean): void => {
      'worklet'
      if (finished !== false) scheduleOnRN(onFinish)
    }
    if (kind === 'flicker') {
      // Neon glow flickers in on mount (ANIMATION.md §4).
      glowK.value = 0
      glowK.value = withSequence(withTiming(0.8, { duration: 133 }), withTiming(0.3, { duration: 133 }), withTiming(1, { duration: 134 }, done))
    } else if (kind === 'cue') {
      // Reduced motion: one 150 ms opacity cue on the whole icon (ANIMATION.md §6).
      opacity.value = reducedMotionSpec.keyframes.opacity?.[0] ?? 0.6
      opacity.value = withTiming(1, { duration: reducedMotionSpec.duration * 1000, easing: Easing.linear }, done)
    } else if (kind === 'draw') {
      const end = drawWindow(Math.max(0, lastPart)).end
      t.value = 0
      t.value = withTiming(end, { duration: end * seconds * 1000, easing: Easing.linear }, done)
    } else if (kind === 'swap') {
      t.value = 0
      t.value = withTiming(1, { duration: seconds * 1000, easing: Easing.linear }, done)
    } else {
      // The whole icon moves: x and y are on the 24 px grid, so they scale with the icon.
      const k = spec.keyframes
      const unit = size / 24
      const runs: [SharedValue<number>, readonly number[], number][] = []
      if (k.x) runs.push([tx, k.x, unit * (preset === 'slide' ? dir : 1)])
      if (k.y) runs.push([ty, k.y, unit])
      if (k.scale) runs.push([scale, k.scale, 1])
      if (k.scaleY) runs.push([scaleY, k.scaleY, 1])
      if (k.rotate) runs.push([rotate, k.rotate, 1])
      if (k.opacity) runs.push([opacity, k.opacity, 1])
      runs.forEach(([sv, values, s], i) => {
        sv.value = (values[0] ?? 0) * s
        sv.value = track(values, spec, seconds, s, i === 0 ? done : undefined)
      })
      if (!runs.length) onFinish()
    }
    // A run is fixed when it mounts: a new run mounts a new Runner (its key changes).
    return () => { for (const sv of [t, tx, ty, scale, scaleY, rotate, opacity, glowK]) cancelAnimation(sv) }
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, [])

  const moving = useAnimatedStyle((): ViewStyle => ({
    opacity: opacity.value,
    transform: [{ translateX: tx.value }, { translateY: ty.value }, { scale: scale.value }, { scaleY: scaleY.value }, { rotate: `${rotate.value}deg` }],
  }))

  return (
    <Animated.View style={[{ width: size, height: size, transformOrigin: origin }, moving]}>
      <Svg width={size} height={size} viewBox="0 0 24 24" fill="none" color={iconStyle === 'neon' ? DEFAULT_INK : (color ?? DEFAULT_INK)} style={SVG_STYLE}>
        {body}
      </Svg>
    </Animated.View>
  )
}

const SVG_STYLE = { overflow: 'visible' } as const

/**
 * The shared component behind every generated React Native icon. The idle icon is a View and a plain react-native-svg
 * tree: no shared values, no animated view, nothing per frame, so a long list of still icons stays cheap. A run
 * mounts a Runner (Reanimated, on the UI thread) and unmounts it at rest. Same props, presets and handle as @fetaui/react.
 */
export function NativeIcon({ icon, iconStyle, tree, dir, size = 24, color, trigger = 'hover', preset = 'draw', speed = 1, ref, style, testID, 'aria-label': ariaLabel, accessibilityLabel }: Props) {
  const enabled = useContext(AnimatedIconsContext)
  const reduced = useReducedMotionSetting()
  const id = useId()
  const [run, setRun] = useState<Run | null>(null)
  const playing = useRef(false)
  const alive = useRef(true)
  const runs = useRef(0)
  const onDone = useRef<(() => void) | null>(null)

  const neon = useMemo(() => iconStyle === 'neon' && has(tree, (r) => r['role$'] === 'glow-outer'), [iconStyle, tree])
  const twoState = useMemo(() => has(tree, (r) => r['state$'] === 'active'), [tree])
  const lastPart = useMemo(() => maxPart(tree), [tree])
  const effective: Preset = presetSpecs[preset].target === 'state' && !twoState ? 'draw' : preset
  const spec = presetSpecs[effective]
  const seconds = spec.duration / Math.max(0.05, speed)

  // Called by the Runner at rest. A flicker never counts as a play, so it only clears itself.
  const finish = useCallback((key: number) => {
    if (!alive.current) return
    setRun((r) => (r && r.key === key ? null : r))
    if (!playing.current) return
    playing.current = false
    const next = onDone.current
    onDone.current = null
    next?.()
  }, [])

  const startAnimation = useCallback(() => {
    if (playing.current) return
    playing.current = true
    const kind: RunKind = reduced ? 'cue' : spec.target === 'paths' ? 'draw' : spec.target === 'state' ? 'swap' : 'move'
    setRun({ kind, key: ++runs.current })
  }, [reduced, spec])

  const stopAnimation = useCallback(() => {
    onDone.current = null
    playing.current = false
    if (alive.current) setRun(null)
  }, [])

  useImperativeHandle(ref, () => ({ startAnimation, stopAnimation }), [startAnimation, stopAnimation])
  useEffect(() => { alive.current = true; return () => { alive.current = false } }, [])

  // The Neon glow flickers in on mount, through a Runner that only animates the glow.
  useEffect(() => {
    if (neon && !reduced) setRun((r) => r ?? { kind: 'flicker', key: ++runs.current })
  }, [neon, reduced])

  const active = enabled ? trigger : 'none'

  // Loops: one at a time, paused while the app is in the background, 400 ms between runs.
  useEffect(() => {
    if (active !== 'loop') return
    let timer: ReturnType<typeof setTimeout> | undefined
    let cued = false
    const tick = (): void => {
      timer = undefined
      if (!isActive(id)) return
      if (reduced) { if (cued) return; cued = true }
      onDone.current = () => { if (isActive(id)) timer = setTimeout(tick, LOOP_PAUSE * 1000) }
      startAnimation()
    }
    const resume = (): void => { if (isActive(id) && timer === undefined && !playing.current) timer = setTimeout(tick, 0) }
    const unsubscribe = subscribe(() => { if (!isActive(id)) { clearTimeout(timer); timer = undefined } else resume() })
    const app = AppState.addEventListener('change', (s) => { if (s === 'active') claim(id, icon); else release(id) })
    claim(id, icon)
    resume()
    return () => { clearTimeout(timer); unsubscribe(); app.remove(); release(id); onDone.current = null }
  }, [active, id, icon, reduced, startAnimation])

  const played = useRef(false)
  const onLayout = active === 'inView' ? () => { if (!played.current) { played.current = true; startAnimation() } } : undefined
  const handlers =
    active === 'hover' ? { onPointerEnter: startAnimation, onTouchStart: startAnimation }
    : active === 'click' ? { onPointerDown: startAnimation, onTouchStart: startAnimation }
    : {}

  const glowColor = iconStyle === 'neon' ? color : undefined
  const idle = useMemo(() => render(tree, { mode: 'idle', anim: null, glowColor }, ''), [tree, glowColor])

  const label = ariaLabel ?? accessibilityLabel
  const a11y = label
    ? { accessible: true, role: 'img' as const, 'aria-label': label }
    : { accessible: false, 'aria-hidden': true, importantForAccessibility: 'no-hide-descendants' as const, accessibilityElementsHidden: true }

  return (
    <View {...a11y} {...handlers} {...(onLayout ? { onLayout } : {})} {...(testID ? { testID } : {})} style={[{ width: size, height: size }, style]}>
      {run ? (
        <Runner
          key={run.key} kind={run.kind} iconStyle={iconStyle} tree={tree} dir={dir} size={size} color={color} preset={effective}
          seconds={seconds} lastPart={lastPart} neon={neon} onFinish={() => finish(run.key)}
        />
      ) : (
        <Svg width={size} height={size} viewBox="0 0 24 24" fill="none" color={iconStyle === 'neon' ? DEFAULT_INK : (color ?? DEFAULT_INK)} style={SVG_STYLE}>
          {idle}
        </Svg>
      )}
    </View>
  )
}
